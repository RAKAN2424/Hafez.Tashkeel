const ARABIC_DIACRITIC_CHAR_RE = /[\u064B-\u065F\u0670\u0640]/;
const KASRA = '\u0650';
const FATHA = '\u064E';
const DAMMA = '\u064F';
const SUKOON = '\u0652';
const SHADDA = '\u0651';

interface ArabicLetterToken {
  base: string;
  marks: string;
}

function tokenizeArabicWord(word: string): ArabicLetterToken[] {
  const tokens: ArabicLetterToken[] = [];
  for (const ch of word) {
    if (ARABIC_DIACRITIC_CHAR_RE.test(ch)) {
      if (tokens.length > 0) {
        tokens[tokens.length - 1].marks += ch;
      }
    } else {
      tokens.push({ base: ch, marks: '' });
    }
  }
  return tokens;
}

/**
 * Intelligently replaces every Qaf (ق) in a single Arabic word with its context-aware
 * Egyptian glottal stop seat: (أ), (ئ), or (ء) based on position, shadda, madd, and vowels.
 */
export function smartConvertEgyptianQafWord(rawWord: string): string {
  if (!rawWord || !rawWord.includes('ق')) return rawWord;

  let leadingPunct = '';
  let trailingPunct = '';
  let w = rawWord;

  while (w.length > 0 && /[،,\.!?؟:؛"'\(\)\[\]{}«»]/.test(w[0])) {
    leadingPunct += w[0];
    w = w.slice(1);
  }
  while (w.length > 0 && /[،,\.!?؟:؛"'\(\)\[\]{}«»]/.test(w[w.length - 1])) {
    trailingPunct = w[w.length - 1] + trailingPunct;
    w = w.slice(0, -1);
  }

  if (!w.includes('ق')) return rawWord;

  // High-confidence common Egyptian colloquial dictionary pre-normalization
  // Handles ambiguous unvocalized words (e.g., يِقول where prefix ي carries colloquial kasra)
  w = w
    .replace(/^(و|ف|ب)?(ي|ت|ن)َقُ?و?ل(وا|ون|ه|ها|ك|ي|هم)?/g, (_, p1 = '', p2, p3 = '') => `${p1}${p2}ِئُوْ${p3 ? `ل${p3}` : 'ل'}`)
    .replace(/دَقِيق(ة|ه)?/g, (_, end = '') => `دِئِيئ${end === 'ة' || end === 'ه' ? 'َه' : ''}`)
    .replace(/حَقِيق(ة|ه)?/g, (_, end = '') => `حَئِيئ${end === 'ة' || end === 'ه' ? 'َه' : ''}`)
    .replace(/رَقِيق(ة|ه)?/g, (_, end = '') => `رَئِيئ${end === 'ة' || end === 'ه' ? 'َه' : ''}`)
    .replace(/بَقِي([تتن]?)/g, 'بَئِي$1')
    .replace(/لَقِي([تتن]?)/g, 'لِئِي$1')
    .replace(/مَعْ?قُول/g, 'مَعْءُول')
    .replace(/مَخْ?لُوق(ة|ه)?/g, (_, end = '') => (end ? 'مَخْلُوءَه' : 'مَخْلُوء'));

  if (!w.includes('ق')) {
    return leadingPunct + w + trailingPunct;
  }

  const tokens = tokenizeArabicWord(w);
  const hasMark = (tok: ArabicLetterToken | undefined, mark: string) => Boolean(tok && tok.marks.includes(mark));
  const isAlif = (tok: ArabicLetterToken | undefined) => Boolean(tok && (tok.base === 'ا' || tok.base === 'أ' || tok.base === 'إ' || tok.base === 'آ'));
  const isYa = (tok: ArabicLetterToken | undefined) => Boolean(tok && (tok.base === 'ي' || tok.base === 'ى' || tok.base === 'ئ'));
  const isWaw = (tok: ArabicLetterToken | undefined) => Boolean(tok && tok.base === 'و');

  for (let i = 0; i < tokens.length; i++) {
    if (tokens[i].base !== 'ق') continue;

    const prev = i > 0 ? tokens[i - 1] : undefined;
    const prev2 = i > 1 ? tokens[i - 2] : undefined;
    const prev3 = i > 2 ? tokens[i - 3] : undefined;
    const next = i < tokens.length - 1 ? tokens[i + 1] : undefined;

    // Recognize word-start or right after definite article "الـ" / "والـ" / "فالـ" / "بالـ" / "للـ"
    const afterDefiniteArticle =
      i === 2 && prev?.base === 'ل' && isAlif(prev2);
    const afterPrefixedDefiniteArticle =
      i === 3 && prev?.base === 'ل' && isAlif(prev2) && Boolean(prev3 && /^[وفبكل]$/.test(prev3.base));
    const afterLelArticle =
      i === 2 && prev?.base === 'ل' && prev2?.base === 'ل';

    const isInitial = i === 0 || afterDefiniteArticle || afterPrefixedDefiniteArticle || afterLelArticle;
    const isFinal = i === tokens.length - 1;

    if (isInitial) {
      // Initial Qaf in Egyptian colloquial -> أ (e.g., أَالْ، أَلْبِيْ، أَمَرْ، الْأَلْبْ)
      tokens[i].base = 'أ';
      continue;
    }

    if (isFinal) {
      if (hasMark(tokens[i], SHADDA)) {
        // Doubled final Qaf (حَقّْ، دَقّْ) -> ءّ
        tokens[i].base = 'ء';
      } else if (prev && (prev.base === 'ا' || prev.base === 'و' || prev.base === 'ي' || prev.base === 'ى')) {
        // After long madd (سَاقْ، فَوْقْ، طَرِيقْ) -> ء
        tokens[i].base = 'ء';
      } else if (hasMark(prev, SUKOON)) {
        // After sukoon (بَرْقْ، فَرْقْ، خَلْقْ) -> ء
        tokens[i].base = 'ء';
      } else if (hasMark(prev, KASRA)) {
        // After short kasra (غِرِقْ، لِحِقْ) -> ئ
        tokens[i].base = 'ئ';
      } else if (hasMark(prev, DAMMA)) {
        // After short damma (أُفُقْ، فُنْدُقْ) -> ء
        tokens[i].base = 'ء';
      } else {
        // After short fatha or unvocalized consonant stem (خَلَقْ -> خَلَأْ، سَرَقْ -> سَرَأْ، نَطَقْ -> نَطَأْ) -> أ
        tokens[i].base = 'أ';
      }
      continue;
    }

    // Medial position (0 < i < tokens.length - 1)
    if (hasMark(tokens[i], KASRA) || hasMark(prev, KASRA) || isYa(prev) || isYa(next)) {
      // Kasra or Ya dominates hamza seat -> ئ (بَئِيتْ، لِئِيتْ، عَائِلْ، طَرِيئِيْ، تِئِيلْ)
      tokens[i].base = 'ئ';
    } else if (prev && prev.base === 'ا') {
      // After long Alif without kasra/ya (طَاقَة -> طَاءَهْ، عَلَاقَة -> عَلَاءَهْ) -> ء
      tokens[i].base = 'ء';
    } else if (hasMark(tokens[i], SHADDA)) {
      // Doubled medial Qaf (سَقَّفْ، تَوَقَّعْ) -> ءّ
      tokens[i].base = 'ء';
    } else if (isWaw(prev) || isWaw(next) || hasMark(tokens[i], DAMMA)) {
      // Adjacent to Waw or Damma without kasra (مَعْءُولْ، فَوْءُهْ، مَخْلُوءَهْ) -> ء
      tokens[i].base = 'ء';
    } else if (hasMark(prev, DAMMA)) {
      // Preceded by short Damma + Fatha/Sukoon -> ء
      tokens[i].base = 'ء';
    } else {
      // Preceded by Fatha/Sukoon and followed by Fatha/Alif/Consonant (نَطَأْتْ، عَأْلْ، وَأْتْ، سَأَطْ، رَأَبَهْ) -> أ
      tokens[i].base = 'أ';
    }
  }

  return leadingPunct + tokens.map((t) => t.base + t.marks).join('') + trailingPunct;
}

/**
 * Converts every word containing Qaf (ق) in a multi-line text using position-aware Egyptian rules (أ / ئ / ء).
 * Skips bracketed song section tags like [Chorus] or *stage directions*.
 */
export function smartConvertEgyptianQaf(text: string): string {
  if (!text || !text.includes('ق')) return text;
  return text
    .split('\n')
    .map((line) => {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('[') || (trimmed.startsWith('*') && trimmed.endsWith('*'))) {
        return line;
      }
      return line
        .split(' ')
        .map((word) => (word.includes('ق') ? smartConvertEgyptianQafWord(word) : word))
        .join(' ');
    })
    .join('\n');
}

export const ensureEgyptianPhoneticRules = (text: string): string => {
  if (!text) return text;
  const sukoon = '\u0652';
  const diacritics = /[\u064B-\u0652\u0670]/;
  const arabicChar = /[\u0600-\u06FF]/;

  return text
    .split('\n')
    .map((line) => {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('[') || (trimmed.startsWith('*') && trimmed.endsWith('*'))) {
        return line;
      }

      const words = line.split(' ');
      return words
        .map((rawWord) => {
          if (!rawWord.trim()) return rawWord;
          if (!arabicChar.test(rawWord)) return rawWord;

          let w = smartConvertEgyptianQafWord(rawWord);

          let trailingPunct = '';
          while (w.length > 0 && /[،,\.!?؟:؛"']/.test(w[w.length - 1])) {
            trailingPunct = w[w.length - 1] + trailingPunct;
            w = w.slice(0, -1);
          }

          if (/[ًٌٍَُِ]$/.test(w)) {
            w = w.replace(/[ًٌٍَُِ]+$/, sukoon);
          }
          if (w.length > 0 && arabicChar.test(w)) {
            if (!w.endsWith(sukoon)) {
              const lastChar = w[w.length - 1];
              if (diacritics.test(lastChar)) {
                w = w.slice(0, -1) + sukoon;
              } else {
                w = w + sukoon;
              }
            }
          }

          return w + trailingPunct;
        })
        .join(' ');
    })
    .join('\n');
};

export const ensureSmartLightDiacriticsRules = (
  text: string,
  originalInput?: string,
  genderPreference: 'auto' | 'masculine' | 'feminine' = 'auto'
): string => {
  if (!text) return text;
  let clean = text;
  const sukoon = '\u0652';
  const diacritics = /[\u064B-\u0652\u0670]/;
  const arabicChar = /[\u0600-\u06FF]/;
  const diacriticsRegex = /[\u064B-\u065F\u0670\u0640]/g;

  let isFeminine = genderPreference === 'feminine';
  if (genderPreference === 'auto') {
    const rawForCheck = (originalInput || text).replace(diacriticsRegex, '');
    const femPatterns = [
      /(^|\s)(إنتِ|انتي|إنتي|يا\s*حبيبتي|حبيبتي|يا\s*بنت|يا\s*أختي|يا\s*عروسة)($|\s|[،,\.!?؟:؛"'])/,
      /(^|\s)(شفتكِ|شفتِك|عايزاكِ|بحبكِ|معاكِ|ليكي|معاكي|عاملة|رايحة|جاية|فاكرة|شايفة|عارفة)($|\s|[،,\.!?؟:؛"'])/,
    ];
    if (femPatterns.some((p) => p.test(rawForCheck))) {
      isFeminine = true;
    }
  }

  clean = clean
    .replace(/[ءئأ][\u064B-\u065F\u0670]*ل[\u064B-\u065F\u0670]*ب/g, 'قَلْب')
    .replace(/م[\u064B-\u065F\u0670]*ع[\u064B-\u065F\u0670]*[ءئأ][\u064B-\u065F\u0670]*و[\u064B-\u065F\u0670]*ل/g, 'مَعْقُول')
    .replace(/[ءئأ][\u064B-\u065F\u0670]*ا[\u064B-\u065F\u0670]*ل/g, 'قَال')
    .replace(/ي[\u064B-\u065F\u0670]*[ءئأ][\u064B-\u065F\u0670]*و[\u064B-\u065F\u0670]*ل/g, 'يِقُول')
    .replace(/ن[\u064B-\u065F\u0670]*ط[\u064B-\u065F\u0670]*[ءئأ]/g, 'نَطَق')
    .replace(/ح[\u064B-\u065F\u0670]*[ءئأّ]/g, 'حَقّ')
    .replace(/ط[\u064B-\u065F\u0670]*ر[\u064B-\u065F\u0670]*ي[\u064B-\u065F\u0670]*[ءئأ]/g, 'طَرِيق')
    .replace(/د[\u064B-\u065F\u0670]*[ءئأ][\u064B-\u065F\u0670]*ي[\u064B-\u065F\u0670]*[ءئأ]/g, 'دَقِيق')
    .replace(/ب[\u064B-\u065F\u0670]*[ءئأ]ي/g, 'بَقِي')
    .replace(/ل[\u064B-\u065F\u0670]*[ءئأ]يت/g, 'لَقِيت')
    .replace(/خ[\u064B-\u065F\u0670]*ل[\u064B-\u065F\u0670]*[ءئأ]/g, 'خَلَق')
    .replace(/[ءئأ][\u064B-\u065F\u0670]*د[\u064B-\u065F\u0670]*ر/g, 'قَدَر');

  if (originalInput && originalInput.includes('ق')) {
    const origWords = originalInput.trim().split(/\s+/);
    const qafBases = origWords
      .map((w) => w.replace(diacriticsRegex, '').replace(/[،,\.!?؟:؛"']/g, ''))
      .filter((w) => w.includes('ق') && w.length >= 2);

    const words = clean.split(' ');
    clean = words
      .map((w) => {
        const pureW = w.replace(diacriticsRegex, '').replace(/[،,\.!?؟:؛"']/g, '');
        for (const base of qafBases) {
          const smartBase = smartConvertEgyptianQafWord(base).replace(diacriticsRegex, '');
          const hamzaBase1 = base.replace(/ق/g, 'ء');
          const hamzaBase2 = base.replace(/ق/g, 'ئ');
          const hamzaBase3 = base.replace(/ق/g, 'أ');
          if (pureW === smartBase || pureW === hamzaBase1 || pureW === hamzaBase2 || pureW === hamzaBase3) {
            let out = '';
            let bi = 0;
            const bareLetters = base.split('');
            for (const ch of w) {
              if (diacriticsRegex.test(ch)) {
                out += ch;
              } else {
                const origCh = bareLetters[bi];
                if (origCh === 'ق' && (ch === 'ء' || ch === 'ئ' || ch === 'أ')) {
                  out += 'ق';
                } else {
                  out += ch;
                }
                bi++;
              }
            }
            return out;
          }
        }
        return w;
      })
      .join(' ');
  }

  clean = clean.replace(/(?<![إا]ن)ت\u064E(?=\s|[،,\.!?؟:؛"']|$)/g, 'ت' + sukoon);

  return clean
    .split('\n')
    .map((line) => {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('[') || (trimmed.startsWith('*') && trimmed.endsWith('*'))) {
        return line;
      }

      const words = line.split(' ');
      return words
        .map((rawWord) => {
          if (!rawWord.trim()) return rawWord;
          if (!arabicChar.test(rawWord)) return rawWord;

          let w = rawWord;

          let leadingPunct = '';
          while (w.length > 0 && /[،,\.!?؟:؛"'\(\)\[\]{}«»]/.test(w[0])) {
            leadingPunct += w[0];
            w = w.slice(1);
          }

          let trailingPunct = '';
          while (w.length > 0 && /[،,\.!?؟:؛"'\(\)\[\]{}«»]/.test(w[w.length - 1])) {
            trailingPunct = w[w.length - 1] + trailingPunct;
            w = w.slice(0, -1);
          }

          const pureWord = w.replace(diacriticsRegex, '');

          const endsWithKaf = /ك$/.test(pureWord);
          if (endsWithKaf) {
            if (/[يا][\u064B-\u0652\u0670]*ك[\u064B-\u0652\u0670]*$/.test(w)) {
              w = isFeminine ? w.replace(/ك[\u064B-\u0652\u0670]*$/, 'كِ') : w.replace(/ك[\u064B-\u0652\u0670]*$/, 'كْ');
            } else {
              w = isFeminine
                ? w.replace(/[َِ]?ك[\u064B-\u0652\u0670]*$/, 'ِكْ')
                : w.replace(/[َِ]?ك[\u064B-\u0652\u0670]*$/, 'َكْ');
            }
          }

          if (/^[إا]نْ?تَ?$/i.test(pureWord)) {
            w = isFeminine ? 'إِنْتِ' : 'إِنْتَ';
          }

          if (/[ًٌٍَُِ]$/.test(w) && !/[َِ]كْ?$/.test(w) && w !== 'إِنْتَ' && w !== 'إِنْتِ') {
            w = w.replace(/[ًٌٍَُِ]+$/, sukoon);
          }

          if (w.length > 0 && arabicChar.test(w) && w !== 'إِنْتَ' && w !== 'إِنْتِ' && !w.endsWith('كِ')) {
            if (!w.endsWith(sukoon)) {
              const lastChar = w[w.length - 1];
              if (diacritics.test(lastChar)) {
                w = w.slice(0, -1) + sukoon;
              } else {
                w = w + sukoon;
              }
            }
          }

          return leadingPunct + w + trailingPunct;
        })
        .join(' ');
    })
    .join('\n');
};

export const ensureConnectedDiacriticsRules = (
  text: string,
  originalInput?: string,
  genderPreference: 'auto' | 'masculine' | 'feminine' = 'auto'
): string => {
  if (!text) return text;
  let clean = text;
  const sukoon = '\u0652';
  const diacritics = /[\u064B-\u0652\u0670]/;
  const arabicChar = /[\u0600-\u06FF]/;
  const diacriticsRegex = /[\u064B-\u065F\u0670\u0640]/g;

  clean = clean
    .replace(/[ءئأ][\u064B-\u065F\u0670]*ل[\u064B-\u065F\u0670]*ب/g, 'قَلْب')
    .replace(/م[\u064B-\u065F\u0670]*ع[\u064B-\u065F\u0670]*[ءئأ][\u064B-\u065F\u0670]*و[\u064B-\u065F\u0670]*ل/g, 'مَعْقُول')
    .replace(/[ءئأ][\u064B-\u065F\u0670]*ا[\u064B-\u065F\u0670]*ل/g, 'قَال')
    .replace(/ي[\u064B-\u065F\u0670]*[ءئأ][\u064B-\u065F\u0670]*و[\u064B-\u065F\u0670]*ل/g, 'يِقُول')
    .replace(/ط[\u064B-\u065F\u0670]*ر[\u064B-\u065F\u0670]*ي[\u064B-\u065F\u0670]*[ءئأ]/g, 'طَرِيق');

  if (originalInput && originalInput.includes('ق')) {
    const origWords = originalInput.trim().split(/\s+/);
    const qafBases = origWords
      .map((w) => w.replace(diacriticsRegex, '').replace(/[،,\.!?؟:؛"']/g, ''))
      .filter((w) => w.includes('ق') && w.length >= 2);

    const words = clean.split(' ');
    clean = words
      .map((w) => {
        const pureW = w.replace(diacriticsRegex, '').replace(/[،,\.!?؟:؛"']/g, '');
        for (const base of qafBases) {
          const smartBase = smartConvertEgyptianQafWord(base).replace(diacriticsRegex, '');
          if (
            pureW === smartBase ||
            pureW === base.replace(/ق/g, 'ء') ||
            pureW === base.replace(/ق/g, 'ئ') ||
            pureW === base.replace(/ق/g, 'أ')
          ) {
            let out = '';
            let bi = 0;
            const bareLetters = base.split('');
            for (const ch of w) {
              if (diacriticsRegex.test(ch)) {
                out += ch;
              } else {
                const origCh = bareLetters[bi];
                out += origCh === 'ق' && (ch === 'ء' || ch === 'ئ' || ch === 'أ') ? 'ق' : ch;
                bi++;
              }
            }
            return out;
          }
        }
        return w;
      })
      .join(' ');
  }

  return clean
    .split('\n')
    .map((line) => {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('[') || (trimmed.startsWith('*') && trimmed.endsWith('*'))) {
        return line;
      }

      const words = line.split(' ');
      return words
        .map((rawWord) => {
          if (!rawWord.trim()) return rawWord;
          if (!arabicChar.test(rawWord)) return rawWord;

          let w = rawWord;
          let trailingPunct = '';
          while (w.length > 0 && /[،,\.!?؟:؛"']/.test(w[w.length - 1])) {
            trailingPunct = w[w.length - 1] + trailingPunct;
            w = w.slice(0, -1);
          }

          const pureWord = w.replace(diacriticsRegex, '');

          if (/ك$/.test(pureWord)) {
            if (genderPreference === 'feminine') {
              w = w.replace(/[َِ]?ك[\u064B-\u0652\u0670]*$/g, 'ِكْ');
            } else {
              w = w.replace(/[َِ]?ك[\u064B-\u0652\u0670]*$/g, 'َكْ');
            }
          }

          if (/[ًٌٍَُِ]$/.test(w) && !/[َِ]كْ$/.test(w)) {
            w = w.replace(/[ًٌٍَُِ]+$/, sukoon);
          }

          if (w.length > 0 && arabicChar.test(w) && !w.endsWith(sukoon)) {
            const lastChar = w[w.length - 1];
            if (diacritics.test(lastChar)) {
              w = w.slice(0, -1) + sukoon;
            } else {
              w = w + sukoon;
            }
          }

          return w + trailingPunct;
        })
        .join(' ');
    })
    .join('\n');
};
